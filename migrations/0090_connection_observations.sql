CREATE TABLE connection_observations (
 id TEXT PRIMARY KEY,
 node_id TEXT NOT NULL,
 core_epoch TEXT NOT NULL,
 connection_id TEXT NOT NULL,
 revision INTEGER NOT NULL CHECK(revision>=1),
 credential_id TEXT NOT NULL,
 user_id TEXT NOT NULL DEFAULT '',
 device_id TEXT NOT NULL DEFAULT '',
 inbound_id TEXT NOT NULL DEFAULT '',
 inbound_protocol TEXT NOT NULL,
 domain TEXT NOT NULL DEFAULT '',
 target_ip TEXT NOT NULL DEFAULT '',
 target_port INTEGER NOT NULL CHECK(target_port>=0 AND target_port<=65535),
 network TEXT NOT NULL CHECK(network IN ('tcp','udp')),
 rule_id TEXT NOT NULL DEFAULT '',
 outbound_id TEXT NOT NULL DEFAULT '',
 outbound_protocol TEXT NOT NULL DEFAULT '',
 chain_id TEXT NOT NULL DEFAULT '',
 egress_known INTEGER NOT NULL CHECK(egress_known IN (0,1)),
 egress_kind TEXT NOT NULL DEFAULT '',
 egress_final_node_id TEXT NOT NULL DEFAULT '',
 egress_association_id TEXT NOT NULL DEFAULT '',
 egress_established INTEGER NOT NULL CHECK(egress_established IN (0,1)),
 egress_failed INTEGER NOT NULL CHECK(egress_failed IN (0,1)),
 egress_failure_code TEXT NOT NULL DEFAULT '',
 action TEXT NOT NULL CHECK(action IN ('Direct','Block','Proxy')),
 allowed INTEGER NOT NULL CHECK(allowed IN (0,1)),
 upload_bytes INTEGER NOT NULL CHECK(upload_bytes>=0),
 download_bytes INTEGER NOT NULL CHECK(download_bytes>=0),
 delivery_known INTEGER NOT NULL CHECK(delivery_known IN (0,1)),
 observed_at TEXT NOT NULL,
 started_at TEXT NOT NULL DEFAULT '',
 ended_at TEXT NOT NULL DEFAULT '',
 interrupted INTEGER NOT NULL CHECK(interrupted IN (0,1)),
 source_sequence INTEGER NOT NULL CHECK(source_sequence>=1),
 source_complete INTEGER NOT NULL CHECK(source_complete IN (0,1)),
 material_json TEXT NOT NULL CHECK(length(CAST(material_json AS BLOB))<=65536),
 first_seen_at TEXT NOT NULL,
 received_at TEXT NOT NULL,
 UNIQUE(node_id, core_epoch, connection_id)
);

CREATE TABLE connection_observation_cursors (
 node_id TEXT NOT NULL,
 core_epoch TEXT NOT NULL,
 high_watermark INTEGER NOT NULL CHECK(high_watermark>=0),
 updated_at TEXT NOT NULL,
 PRIMARY KEY(node_id, core_epoch)
);

CREATE TABLE connection_observation_gaps (
 id TEXT PRIMARY KEY,
 node_id TEXT NOT NULL,
 core_epoch TEXT NOT NULL,
 from_sequence INTEGER NOT NULL CHECK(from_sequence>=1),
 to_sequence INTEGER NOT NULL CHECK(to_sequence>=from_sequence),
 reason TEXT NOT NULL,
 recorded_at TEXT NOT NULL,
 UNIQUE(node_id, core_epoch, from_sequence, to_sequence)
);

CREATE TABLE egress_associations (
 association_id TEXT PRIMARY KEY,
 origin_node_id TEXT NOT NULL,
 origin_core_epoch TEXT NOT NULL,
 origin_connection_id TEXT NOT NULL,
 entry_revision INTEGER NOT NULL CHECK(entry_revision>=1),
 target_digest TEXT NOT NULL CHECK(length(target_digest)=64),
 network TEXT NOT NULL CHECK(network IN ('tcp','udp')),
 hop_index INTEGER NOT NULL CHECK(hop_index>=0),
 max_hops INTEGER NOT NULL CHECK(max_hops>=1),
 expected_next_node_id TEXT NOT NULL,
 observed_node_id TEXT NOT NULL,
 relay_credential_id TEXT NOT NULL,
 route_selected INTEGER NOT NULL CHECK(route_selected IN (0,1)),
 outbound_established INTEGER NOT NULL CHECK(outbound_established IN (0,1)),
 failed INTEGER NOT NULL CHECK(failed IN (0,1)),
 failure_code TEXT NOT NULL DEFAULT '',
 final_egress_known INTEGER NOT NULL CHECK(final_egress_known IN (0,1)),
 final_egress_node_id TEXT NOT NULL DEFAULT '',
 proof_digest TEXT NOT NULL CHECK(length(proof_digest)=64),
 observed_at TEXT NOT NULL,
 recorded_at TEXT NOT NULL,
 UNIQUE(origin_node_id, origin_core_epoch, origin_connection_id, hop_index)
);
