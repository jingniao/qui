-- Minute telemetry remains exact for 24h; older completed UTC 5m buckets retain weighted statistics.
CREATE TABLE node_metric_rollups (
 node_id TEXT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
 bucket TEXT NOT NULL,
 samples INTEGER NOT NULL CHECK(samples>0),
 cpu_percent_sum REAL,
 cpu_percent_count INTEGER NOT NULL CHECK(cpu_percent_count>=0),
 cpu_percent_min REAL,
 cpu_percent_max REAL,
 memory_percent_sum REAL,
 memory_percent_count INTEGER NOT NULL CHECK(memory_percent_count>=0),
 memory_percent_min REAL,
 memory_percent_max REAL,
 disk_percent_sum REAL,
 disk_percent_count INTEGER NOT NULL CHECK(disk_percent_count>=0),
 disk_percent_min REAL,
 disk_percent_max REAL,
 memory_used_bytes_sum REAL,
 memory_used_bytes_count INTEGER NOT NULL CHECK(memory_used_bytes_count>=0),
 memory_used_bytes_min REAL,
 memory_used_bytes_max REAL,
 swap_used_bytes_sum REAL,
 swap_used_bytes_count INTEGER NOT NULL CHECK(swap_used_bytes_count>=0),
 swap_used_bytes_min REAL,
 swap_used_bytes_max REAL,
 disk_used_bytes_sum REAL,
 disk_used_bytes_count INTEGER NOT NULL CHECK(disk_used_bytes_count>=0),
 disk_used_bytes_min REAL,
 disk_used_bytes_max REAL,
 load1_sum REAL,
 load1_count INTEGER NOT NULL CHECK(load1_count>=0),
 load1_min REAL,
 load1_max REAL,
 process_count_sum REAL,
 process_count_count INTEGER NOT NULL CHECK(process_count_count>=0),
 process_count_min REAL,
 process_count_max REAL,
 tcp_connections_sum REAL,
 tcp_connections_count INTEGER NOT NULL CHECK(tcp_connections_count>=0),
 tcp_connections_min REAL,
 tcp_connections_max REAL,
 udp_sockets_sum REAL,
 udp_sockets_count INTEGER NOT NULL CHECK(udp_sockets_count>=0),
 udp_sockets_min REAL,
 udp_sockets_max REAL,
 active_connections_sum REAL,
 active_connections_count INTEGER NOT NULL CHECK(active_connections_count>=0),
 active_connections_min REAL,
 active_connections_max REAL,
 rx_bytes_per_second_sum REAL,
 rx_bytes_per_second_count INTEGER NOT NULL CHECK(rx_bytes_per_second_count>=0),
 rx_bytes_per_second_min REAL,
 rx_bytes_per_second_max REAL,
 tx_bytes_per_second_sum REAL,
 tx_bytes_per_second_count INTEGER NOT NULL CHECK(tx_bytes_per_second_count>=0),
 tx_bytes_per_second_min REAL,
 tx_bytes_per_second_max REAL,
 tcp_retrans_percent_sum REAL,
 tcp_retrans_percent_count INTEGER NOT NULL CHECK(tcp_retrans_percent_count>=0),
 tcp_retrans_percent_min REAL,
 tcp_retrans_percent_max REAL,
 tail_at TEXT NOT NULL,
 tail_out INTEGER,
 tail_retrans INTEGER,
 PRIMARY KEY(node_id,bucket)
);
CREATE INDEX node_metric_rollups_retention ON node_metric_rollups(bucket);
CREATE TABLE node_latency_rollups (
 node_id TEXT NOT NULL REFERENCES nodes(id) ON DELETE CASCADE,
 target_id TEXT NOT NULL REFERENCES probe_targets(id) ON DELETE CASCADE,
 bucket TEXT NOT NULL,
 samples INTEGER NOT NULL CHECK(samples>0),
 sent INTEGER NOT NULL CHECK(sent>=0),
 failed INTEGER NOT NULL CHECK(failed BETWEEN 0 AND sent),
 median_sum REAL,
 median_count INTEGER NOT NULL CHECK(median_count>=0),
 median_min REAL,
 median_max REAL,
 PRIMARY KEY(node_id,target_id,bucket)
);
CREATE INDEX node_latency_rollups_retention ON node_latency_rollups(bucket);
CREATE INDEX node_latency_samples_at_target ON node_latency_samples(at,node_id,target_id);
