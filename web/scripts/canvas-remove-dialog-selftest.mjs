import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
import { ref } from 'vue';
import { parse } from '@vue/compiler-sfc';

const file = new URL('../src/modules/proxy/components/relay/CanvasRemoveDialog.vue', import.meta.url);
const source = readFileSync(file, 'utf8');
const descriptor = parse(source).descriptor;
let code = ts.transpileModule(descriptor.scriptSetup.content, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext } }).outputText;
code = code.replace(/^import .*;\r?\n/gm, '').replace('const props = defineProps();', '').replace('const emit = defineEmits();', '');
const create = new Function('props', 'emit', 'canvasAPI', 'APIError', 'ref', `${code}\nreturn { remove, close, busy, error };`);
class APIError extends Error { constructor(code) { super('original error'); this.code = code; } }
const scheme = { id: 's', name: '方案', updatedAt: 'version' };
const events = [];
const calls = [];
let finish;
const result = { schemeId: 's', removed: true, pendingNodes: [{ nodeId: 'offline', name: '离线节点', reason: 'offline' }] };
const dialog = create({ scheme }, (...event) => events.push(event), { remove: async (...args) => { calls.push(args); return new Promise(resolve => { finish = resolve; }); } }, APIError, ref);
assert.deepEqual(calls, [], 'opening requires no plan or status request');
const completion = dialog.remove();
assert.deepEqual(calls, [['s', { updatedAt: 'version' }]], 'confirmation sends only optimistic version');
assert.equal(dialog.busy.value, true);
dialog.close();
await dialog.remove();
assert.equal(calls.length, 1, 'in-flight action cannot submit again');
assert.deepEqual(events, [], 'in-flight dialog remains attached until response');
finish(result);
await completion;
assert.deepEqual(events, [['removed', result]], 'success immediately hands result to parent for close and refresh');
assert.equal(dialog.busy.value, false);
const stale = create({ scheme }, (...event) => events.push(event), { remove: async () => { throw new APIError('stale_scheme'); } }, APIError, ref);
await stale.remove();
assert.equal(stale.error.value, '方案已被修改，请刷新后重试');
assert.equal(events.length, 1, 'stale response keeps dialog open');
const failed = create({ scheme }, () => assert.fail('failed request cannot emit removal'), { remove: async () => { throw new Error('请求失败'); } }, APIError, ref);
await failed.remove();
assert.equal(failed.error.value, '请求失败');
assert.equal(failed.busy.value, false);
const canceled = [];
create({ scheme }, (...event) => canceled.push(event), { remove: () => assert.fail('cancel cannot request removal') }, APIError, ref).close();
assert.deepEqual(canceled, [['close']]);
console.log('PASS canvas remove dialog: single POST, updatedAt only, immediate result, cancel, busy guard, stale and original error');
