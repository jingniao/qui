import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';

const source = readFileSync(new URL('../src/modules/proxy/canvasRemove.ts', import.meta.url), 'utf8');
const code = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2020, module: ts.ModuleKind.ESNext } }).outputText;
const { canvasRemoveView, canConfirmCanvasRemove, canvasRestoreOptions } = await import(`data:text/javascript;base64,${Buffer.from(code).toString('base64')}`);
const entry = { bindingId: 'binding', instanceId: 'instance', inboundId: 'in', nodeId: 'a', name: '入口', protocol: 'vless', core: 'xray', listen: '::', port: 443, mode: 'create', action: 'delete', currentRoute: 'out', groups: [{ id: 'g', name: '分组' }], changes: ['端口已修改'], referrers: [] };
const plan = { ok: false, schemeId: 's', updatedAt: 'version', entries: [entry], objects: [{ kind: 'outbound', id: 'out', nodeId: 'a', name: '通道', port: 80, tunnelId: 't', keep: false, referrers: [] }, { kind: 'inbound', id: 'shared', nodeId: 'b', name: '共享监听', port: 443, tunnelId: 't', keep: true, referrers: [{ kind: 'scheme', id: 'other', name: '其他方案' }] }], nodes: ['a', 'b'], changeDetectionRule: '基线说明' };
const before = JSON.stringify(plan);
const view = canvasRemoveView(plan, id => `服务器 ${id}`);
assert.match(view.entries[0].actionText, /删除/);
assert.match(view.entries[0].groupsText, /分组/);
assert.equal(view.removeObjects.length, 1);
assert.equal(view.keepObjects.length, 1);
assert.match(view.keepObjects[0].referrersText, /其他方案/);
assert.deepEqual(view.nodes, [{ id: 'a', name: '服务器 a', order: 1 }, { id: 'b', name: '服务器 b', order: 2 }]);
assert.deepEqual(view.changes, ['入口：端口已修改']);
assert.equal(JSON.stringify(plan), before);
assert.equal(canConfirmCanvasRemove(plan, {}, false), false);
assert.equal(canConfirmCanvasRemove(plan, {}, true), true);
const unchanged = { ...plan, ok: true, entries: [{ ...entry, changes: [] }] };
assert.equal(canConfirmCanvasRemove(unchanged, {}, false), true);
assert.deepEqual(canvasRemoveView(unchanged).changes, []);
assert.equal(canvasRemoveView(unchanged).entries[0].groupsText, '分组');
const dialog = readFileSync(new URL('../src/modules/proxy/components/relay/CanvasRemoveDialog.vue', import.meta.url), 'utf8');
assert.match(dialog, /<section v-if="view\.changes\.length"[\s\S]*?v-model="acknowledged"[\s\S]*?<\/section>/);
assert.equal(canConfirmCanvasRemove({ ...plan, entries: [{ ...entry, referrers: [{ kind: 'outbound', id: 'o', name: '外部引用' }] }] }, {}, true), false);
const reuse = { ...entry, bindingId: 'legacy:instance', mode: 'reuse', action: 'restore', changes: null, groups: null, referrers: null, needsRestoreTarget: true, restoreReason: '原出站缺失' };
const restorePlan = { ...plan, entries: [reuse] };
assert.equal(canConfirmCanvasRemove(restorePlan, {}, true), false);
assert.equal(canConfirmCanvasRemove(restorePlan, { 'legacy:instance': '' }, true), false);
assert.equal(canConfirmCanvasRemove(restorePlan, { 'legacy:instance': 'direct' }, false), true);
assert.match(canvasRemoveView({ ...restorePlan, entries: [{ ...reuse, restoreTarget: 'chain:c' }] }, undefined, route => `目标 ${route}`).entries[0].actionText, /目标 chain:c/);
assert.equal(canConfirmCanvasRemove({ ...plan, entries: [], objects: [] }, {}, true), false);
assert.equal(canConfirmCanvasRemove({ ...plan, entries: [], ok: false }, {}, true), false);
const options = canvasRestoreOptions('a', [{ id: 'oa', name: '出站 A', nodeId: 'a', enabled: true }, { id: 'ob', nodeId: 'b', enabled: true }, { id: 'off', nodeId: 'a', enabled: false }], [{ id: 'ca', name: '链 A', nodeIds: ['a', 'b'], enabled: true }, { id: 'cb', nodeIds: ['b', 'a'], enabled: true }, { id: 'off', nodeIds: ['a'], enabled: false }]);
assert.deepEqual(options.map(item => item.value), ['direct', 'block', 'oa', 'chain:ca']);
console.log('PASS canvas removal: entry deletion/restoration, shared references, server order, change acknowledgement, blockers and restore options');
