import assert from 'node:assert/strict';
import { readFileSync, readdirSync, existsSync } from 'node:fs';
import ts from 'typescript';

const source = file => readFileSync(new URL('../src/modules/tunnels/' + file, import.meta.url), 'utf8');
const transpile = text => ts.transpileModule(text, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext } }).outputText;
const dataURL = text => `data:text/javascript;base64,${Buffer.from(text).toString('base64')}`;
const modelURL = dataURL(transpile(source('model.ts')));
const m = await import(modelURL);
const tunnel = { id: 'a', name: '测试隧道', hops: [{ nodeName: 'HK' }, { nodeName: 'JP' }] };
assert.equal(m.routeLabel(tunnel), 'HK → JP');
assert.equal(m.routeLabel({ hops: [...tunnel.hops, { nodeName: 'US' }] }), 'HK → JP → US');
assert.equal(m.endpoint('2001:db8::1', 443), '[2001:db8::1]:443');
const grouped = m.groupRules([{ id: 'r1', tunnelId: 'a' }, { id: 'r2', tunnelId: null }, { id: 'r3', tunnelId: 'a' }], [tunnel]);
assert.equal(grouped.length, 2);
assert.deepEqual(grouped[0].rules.map(r => r.id), ['r1', 'r3']);
assert.equal(grouped[1].name, '直接转发');
assert.equal(grouped[0].route, 'HK → JP');
for (const port of [undefined, '', 0, -1, 65536, NaN, 1.1]) assert.match(m.portValidation('hk', port), /端口/);
for (const port of [1, 443, 65535]) assert.equal(m.portValidation('hk', port), '');
assert.match(m.portValidation('', 443), /服务器/);
const used = { nodeId: 'hk', port: 443, free: false, usedBy: { kind: 'rule', id: 'r', name: '已有规则' } };
assert.equal(m.portValidation('hk', 443, used), '已被 已有规则 占用');
assert.equal(m.portValidation('hk', 443, used, { kind: 'rule', id: 'r' }), '');
assert.match(m.portValidation('hk', 443, used, { kind: 'tunnel', id: 'r' }), /占用/);
assert.equal(m.portValidation('jp', 443, used), '', 'old node check must not affect a new node');
// Execute PortControl.validate itself: auto-empty must skip the port-check API,
// but manual-empty and an occupied suggestion still fail.
const controlSource = source('components/PortControl.vue').split('<script setup lang="ts">')[1].split('</script>')[0];
const controlCode = transpile(`
  const props = { nodeId: 'hk', mode: 'auto', port: undefined };
  const ref = value => ({ value }), watch = () => {}, defineExpose = () => {};
  const defineProps = () => props, defineEmits = () => () => {};
  let checks = 0;
  const portAPI = { check: async () => { checks++; return ${JSON.stringify(used)}; } };
  const tunnelError = e => e.message;
  const portValidation = ${m.portValidation.toString()};
  const validPort = ${m.validPort.toString()};
  ${controlSource.replace(/^import .*;\r?\n/gm, '').replace(/^const props = defineProps.*;$/m, '')}
  export { props, validate, checks };
`);
const control = await import(dataURL(controlCode));
assert.equal(await control.validate(), true);
assert.equal(control.checks, 0);
control.props.mode = 'manual';
assert.equal(await control.validate(), false);
control.props.mode = 'auto'; control.props.port = 443;
assert.equal(await control.validate(), false);
assert.equal(control.checks, 1);
control.props.nodeId = '';
assert.equal(await control.validate(), false);
const plan = { servers: [{ nodeId: 'hk', order: 2, listeners: [], routes: [], changes: [] }, { nodeId: 'jp', order: 1, listeners: [{ port: 30000, network: 'both', purpose: '隧道' }], routes: ['HK → JP'], changes: [{ action: 'create', kind: '隧道', name: '测试' }] }] };
const frozen = JSON.stringify(plan), rows = m.planToRows(plan);
assert.deepEqual(rows.map(r => r.nodeId), ['jp', 'hk']);
assert.equal(rows[0].listenerText, '30000 / BOTH / 隧道');
assert.equal(rows[0].changeText, '新增 隧道 · 测试');
assert.equal(JSON.stringify(plan), frozen);
assert.deepEqual(Object.values(m.publishStatuses).map(s => s.label), ['待删除', '草稿', '已修改', '待发布', '已发布']);

// The same in-memory transpilation approach as the other web selftests, with
// only the runtime dependencies replaced by data URLs.
const clientURL = dataURL(transpile(readFileSync(new URL('../src/app/apiClient.ts', import.meta.url), 'utf8')));
const mockCode = transpile(source('mock.ts')).replace("'../../app/apiClient'", JSON.stringify(clientURL)).replace("'./model'", JSON.stringify(modelURL));
const { mockRequest: call, mockChoices } = await import(dataURL(mockCode));
assert.deepEqual(mockChoices().nodes.map(n => n.name), ['HK', 'JP', 'US']);
assert.equal(mockChoices().inbounds.length, 6);
const initial = await call('/tunnels', 'GET');
assert.equal(initial.items.length, 1);
assert.equal((await call('/tunnel-rules', 'GET')).items.length, 2);
await assert.rejects(call('/tunnels/hk-jp', 'DELETE'), e => e.code === 'tunnel_in_use' && e.details.rules[0].id === 'us-relay');
await assert.rejects(call('/tunnels/hk-jp/rotate-credentials', 'POST', { updatedAt: 'old' }), e => e.code === 'stale');
const rotated = await call('/tunnels/hk-jp/rotate-credentials', 'POST', { updatedAt: initial.items[0].updatedAt });
assert.equal(rotated.status, 'modified');
assert.equal(rotated.credentials.generation, 1);
const occupied = await call('/nodes/us/ports/check?port=443', 'GET');
assert.equal(occupied.free, false);
assert.equal(occupied.usedBy.kind, 'inbound');
const suggestion = await call('/nodes/us/ports/allocate', 'POST', { count: 2 });
assert.equal(suggestion.ports.length, 2);
assert.equal((await call(`/nodes/us/ports/check?port=${suggestion.ports[0]}`, 'GET')).free, true, 'suggestion reserves nothing');
const created = await call('/tunnels', 'POST', { name: '三跳', transport: 'tls', hops: [{ role: 'entry', nodeId: 'us', portMode: 'auto' }, { role: 'mid', nodeId: 'hk', portMode: 'auto' }, { role: 'exit', nodeId: 'jp', portMode: 'auto' }] });
assert.equal(created.hops[0].listenPort, null);
assert.equal(created.hops.length, 3);
const edited = await call(`/tunnels/${created.id}`, 'PUT', { name: '三跳已编辑', transport: 'tls', updatedAt: created.updatedAt, hops: created.hops.map(h => ({ ...h, listenPort: h.listenPort ?? undefined })) });
assert.equal(edited.name, '三跳已编辑');
await assert.rejects(call(`/tunnels/${created.id}`, 'PUT', { ...edited, updatedAt: created.updatedAt }), e => e.code === 'stale');
await assert.rejects(call('/tunnel-rules', 'POST', { name: '冲突', entryNodeId: 'us', portMode: 'manual', listenPort: 443, network: 'tcp', tunnelId: null, target: { mode: 'manual', host: 'example.com', port: 443 }, subscriptionVisible: false, enabled: true }), e => e.code === 'port_in_use');
const relay = await call('/nodes/jp/relays', 'POST', { tunnelId: 'hk-jp', inboundId: 'jp-socks5', portMode: 'auto', subscriptionVisible: true });
assert.equal(relay.rule.target.host, '127.0.0.1', 'exit matches destination: loopback');
assert.equal(relay.rule.ownerNodeId, 'jp');
assert.ok(relay.shareLink.startsWith('socks5://'));
assert.equal((await call('/nodes/jp/relays', 'GET')).items.length, 1);
const changedRule = await call(`/tunnel-rules/${relay.rule.id}`, 'PUT', { ...relay.rule, name: '已编辑的规则', target: { mode: 'linked', inboundId: 'jp-socks5' } });
assert.equal(changedRule.name, '已编辑的规则');
await assert.rejects(call(`/tunnel-rules/${relay.rule.id}`, 'PUT', { ...relay.rule, target: { mode: 'linked', inboundId: 'jp-socks5' } }), e => e.code === 'stale');
await call(`/tunnel-rules/${relay.rule.id}`, 'DELETE');
assert.equal((await call('/nodes/jp/relays', 'GET')).items.length, 0);
assert.ok((await call('/tunnel-rules?tunnelId=hk-jp&nodeId=hk', 'GET')).items.every(r => r.entryNodeId === 'hk' && r.tunnelId === 'hk-jp'));
const selection = { tunnelIds: [created.id], ruleIds: [] };
const preview = await call('/tunnels/plan', 'POST', selection);
assert.equal(preview.ok, true);
assert.deepEqual(preview.servers.map(s => s.nodeId), ['jp', 'hk', 'us']);
assert.ok((await call('/tunnels/publish', 'POST', selection)).servers.every(s => s.status === 'applied'));
assert.ok((await call('/tunnels/publish', 'POST', selection)).servers.every(s => s.status === 'unchanged'));
await call('/tunnels/' + created.id, 'DELETE');
assert.equal((await call('/tunnels', 'GET')).items.find(t => t.id === created.id).status, 'pending_delete');
await assert.rejects(call('/tunnel-rules', 'POST', { name: '不能关联', tunnelId: created.id, entryNodeId: 'us' }), e => e.code === 'pending_delete');
assert.equal((await call(`/nodes/jp/ports/check?port=${created.hops[2].listenPort}`, 'GET')).free, false, 'delete keeps port claim until cleanup publish');
assert.ok((await call('/tunnels/plan', 'POST', selection)).servers.some(s => s.changes.some(c => c.action === 'remove')));
await call('/tunnels/publish', 'POST', selection);
assert.equal((await call(`/nodes/jp/ports/check?port=${created.hops[2].listenPort}`, 'GET')).free, true);
assert.ok(!(await call('/tunnels', 'GET')).items.some(t => t.id === created.id));
await call('/tunnel-rules/us-relay', 'DELETE');
assert.equal((await call('/tunnel-rules', 'GET')).items.find(r => r.id === 'us-relay').status, 'pending_delete');
assert.equal((await call('/nodes/us/relays', 'GET')).items[0].rule.status, 'pending_delete');
await assert.rejects(call('/tunnels/hk-jp', 'DELETE'), e => e.code === 'tunnel_in_use');
await call('/tunnels/publish', 'POST', { tunnelIds: [], ruleIds: ['us-relay'] });
assert.ok(!(await call('/tunnel-rules', 'GET')).items.some(r => r.id === 'us-relay'));
assert.equal((await call('/nodes/hk/ports/check?port=30001', 'GET')).free, true);

const api = source('api.ts');
assert.match(api, /import\.meta\.env\.DEV && localStorage\['qui\.mock\.tunnels'\] === '1'/);
assert.equal((api.match(/import\('\.\/mock'\)/g) || []).length, 2);
for (const line of api.split('\n').filter(line => line.includes("import('./mock')"))) assert.match(line, /if \(import\.meta\.env\.DEV && mockEnabled\(\)\)/, 'every mock import needs a compile-time DEV guard');
const dist = new URL('../dist/assets/', import.meta.url);
assert.ok(existsSync(dist), 'run npm run build first so production assets can be inspected');
const assets = readdirSync(dist);
assert.ok(assets.some(f => f.startsWith('TunnelsPage-') && f.endsWith('.js')), 'the build must contain the new page');
for (const file of assets.filter(f => f.endsWith('.js'))) {
  assert.doesNotMatch(file, /^mock-/, 'no mock chunk in production');
  assert.doesNotMatch(readFileSync(new URL(file, dist), 'utf8'), /QUI_TUNNELS_DEV_FIXTURES|qui\.mock\.tunnels|mock\.tunnel/, 'production must exclude mock code and fixture switch');
}
console.log('PASS tunnels: route/group/port/plan helpers, mock CRUD/relays/conflicts/stale/publish/cleanup, production mock exclusion');
